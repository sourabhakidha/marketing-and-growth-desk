"""Generates supabase/migrations/20261025000100_knowledge_seed.sql from the seed texts."""
import pathlib, sys
here = pathlib.Path(__file__).parent
sys.path.insert(0, str(here))
from script_patterns import PATTERNS, to_text  # noqa: E402

def q(s): return "'" + s.replace("'", "''") + "'"

brand = (here / "brand_guidelines.md").read_text(encoding="utf-8").strip()
rows = [f"  ('brand_guidelines', {q('Akidha AI-Ready Brand Guidelines (v1.0)')}, {q(brand)}, null, '{{voice,guardrails,visual}}', {q('Akidha AI Ready Brand Guidelines.docx.pdf (Marketing Desk project). Colour values provisional.')})"]
for p in PATTERNS:
    rows.append(f"  ('script_pattern', {q(p[1])}, {q(to_text(p))}, {q(p[2])}, '{{script,{p[0].lower().replace(' ', '_').replace('/', '_')}}}', {q('Pattern summary of JulyAugSept - Scripts Master.pdf; not a script to reuse, not evidence.')})")
sql = """-- =============================================================================
-- Knowledge base seed for AI drafting (decision D-021). Generated by
-- scripts/seed/build_knowledge_sql.py — edit the seed files, then regenerate.
-- Brand guidelines (full working text) + pattern summaries of the Jul–Sep 2026
-- Scripts Master. Script entries carry no prices, savings or operational claims.
-- Touches ONLY marketing_os.
-- =============================================================================
insert into marketing_os.knowledge_documents (kind, title, content, language, tags, source_note) values
""" + ",\n".join(rows) + ";\n"
out = here.parent.parent / "supabase" / "migrations" / "20261025000100_knowledge_seed.sql"
out.write_text(sql, encoding="utf-8")
print(out, len(rows), "rows", len(sql), "chars")
